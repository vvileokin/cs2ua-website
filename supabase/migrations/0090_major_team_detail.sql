-- CS2 UA — розклад очок VRS по команді, для сторінки /major/[team].
-- Run in Supabase → SQL Editor. Depends on nothing; 0077 поруч, але окремо.
--
-- Навіщо окрема таблиця, коли major_projection уже є. Та відповідає на питання
-- «де команда стоїть». Ця — на питання «чому саме там і що це змінить»: з яких
-- рядків складаються очки, скільком із них лишилось жити, що дасть кожне місце
-- на кожному турнірі попереду і скільком відсоткам проходу вартий окремий матч.
--
-- Це стало можливим тільки 28 жовтня 2026, коли знайшлося, що HLTV публікує
-- повний розклад VRS по команді (/valve-ranking/teams/details/...). До того
-- модель рахувала приріст одним каліброваним кроком і сказати «ця перемога
-- дасть вам сорок три очки, а ось ця — нуль» не могла в принципі.
--
-- Форма — один jsonb на команду, а не нормалізовані таблиці. Усередині лежать
-- п'ять різних за формою списків (рядки компонентів, драбини турнірів, матчі,
-- переслідувачі), вони читаються завжди разом і завжди цілком, і жоден запит
-- ніколи не питатиме «усі команди, в яких третій рядок LAN старший за місяць».
-- Нормалізація тут купила б лише п'ять таблиць і жодної вибірки.

create table if not exists public.major_team_detail (
  -- Слаг із каталогу команд сайту, щоб маршрут був /major/natus, а не
  -- /major/Natus%20Vincere. Назву з HLTV payload несе всередині.
  slug        text        primary key,
  as_of       date        not null,          -- дата зрізу VRS
  runs        bigint      not null,          -- прогонів у симуляції
  payload     jsonb       not null,
  computed_at timestamptz not null default now()
);

comment on table public.major_team_detail is
  'Розклад очок VRS і ціна майбутніх результатів по команді. Заповнює vrs-model/team-detail.mjs через scripts/major-team-push.mjs.';

-- ---------------------------------------------------------------------------
-- Доступ
-- ---------------------------------------------------------------------------
-- Читати може будь-хто: це та сама публічна таблиця, що й прогноз. Писати —
-- тільки service-role, тобто скрипт заливки; політики на запис немає зовсім,
-- і це навмисно.
alter table public.major_team_detail enable row level security;

drop policy if exists "major_team_detail read" on public.major_team_detail;
create policy "major_team_detail read"
  on public.major_team_detail for select
  using (true);
