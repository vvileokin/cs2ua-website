-- CS2 UA — розіграш може вдягтися в мейджор. Run in Supabase → SQL Editor.
-- Requires 0034, 0035, 0087.
--
-- 0087 розширив перелік скінів до чотирьох і залишив по собі попередження:
-- «список той самий, що в каталозі сайту, і міняти його доведеться разом із
-- ним; наступного разу першим зламається саме цей рядок». Так і сталося — у
-- каталозі відтоді з'явилися `pgl` і `major`, а перевірка про них не знає, і
-- розіграш у кольорах мейджора просто не вставляється.
--
-- Додаю обидва, а не лише той, що потрібен сьогодні: `pgl` існує в каталозі
-- стільки ж часу й зламався б наступним.
--
-- Правило лишається дублем того, що в `EventSkin`, і це свідомо: база не може
-- прочитати типи застосунку, а мовчки пускати будь-який текст у колонку, за
-- якою малюється оформлення, — гірше. Попередження з 0087 переноситься сюди
-- без змін.

alter table public.giveaways
  drop constraint if exists giveaways_skin_check;
alter table public.giveaways
  add constraint giveaways_skin_check
  check (skin is null or skin in ('blast', 'ewc', 'porto', 'epl', 'pgl', 'major'));

