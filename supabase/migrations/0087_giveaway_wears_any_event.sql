-- 0034 дозволив картці розіграшу вдягатися в подію і перелічив тодішні дві:
-- blast і ewc. Відтоді з'явилися porto й epl, а перевірка лишилася старою — і
-- розіграш у кольорах EPL просто не вставлявся.
--
-- Список той самий, що в каталозі сайту (EventSkin), і міняти його доведеться
-- разом із ним. Нагадування про це — тут, бо наступного разу першим зламається
-- саме цей рядок.
-- ---------------------------------------------------------------------------

alter table public.giveaways
  drop constraint if exists giveaways_skin_check;
alter table public.giveaways
  add constraint giveaways_skin_check
  check (skin is null or skin in ('blast', 'ewc', 'porto', 'epl'));
