-- CS2 UA — PGL Masters Bucharest 2026 відкривається, у всіх знову по 500.
-- Run in Supabase → SQL Editor. Requires 0060, 0073, 0075, 0079, 0082.
--
-- EPL S24 лишив гаманці відкритими: 359 848 івент-поінтів на 653 профілях,
-- із них 171 устиг зробити хоч одну дію і стоїть на дошці. Витратити їх нема
-- де — з 0079 звичайна ставка живе на сезонних, а івентові приймає лише матч
-- турніру зі списку `event_tournaments`, і EPL у ньому вже дограний.
--
-- Прибуток із цих поінтів давно в сезонній колонці: `settle_bets` (0075)
-- одразу кладе `payout - stake` у `points`, а програна ставка сезонних не
-- знімає. Тому закриття нічого не виплачує — воно обнуляє гаманець до нового
-- внеску. Саме так закривали Porto і EWC, і 0070 існує для того, щоб ніхто не
-- заплатив за той самий турнір удруге.
--
-- Отже:
--
--     кожному 500 на PGL Masters Bucharest
--     дошка порожня, поки хтось не зробить першу дію
--     ставка на матч PGL списує івент-поінти, на будь-який інший — сезонні

begin;

-- ---------------------------------------------------------------------------
-- Новий внесок
-- ---------------------------------------------------------------------------
-- Рівно 500 кожному, включно з тими, хто лишився з нулем: турнір має бути
-- змаганням у читанні гри, а не в тому, хто скільки приніс із жовтня.
--
-- `event_joined_at = null` — це і є те, що спорожняє дошку. Колонка стоїть не
-- на балансі, а на першій дії: ставка, дуель або зарахований прогноз. Без
-- скидання на дошці PGL з першої ж хвилини стояв би 171 профіль із чужими
-- балансами, і перший, хто зайде, побачив би готовий топ, у якому ще ніхто не
-- поставив жодного поінта на цей турнір.
update public.profiles
   set event_points = 500,
       event_joined_at = null;

-- Нові акаунти, що з'являться під час турніру, отримують те саме. Типове
-- значення стоїть з 0060 і не змінювалось — рядок лишається для повноти.
alter table public.profiles alter column event_points set default 500;

-- ---------------------------------------------------------------------------
-- Чий це гаманець
-- ---------------------------------------------------------------------------
-- Список із 0079: ставка на матч турніру зі списку списує івент-поінти, решта
-- сайту живе на сезонних. Порожній рядок тут означав би мовчазний перехід
-- усього турніру на сезонну валюту, тому слаґ додається тим самим рухом, що й
-- внесок. Слаґ — рівно той, що в `allTournaments`.
insert into public.event_tournaments (slug) values ('pgl-masters-bucharest-2026')
on conflict (slug) do nothing;

commit;

