-- CS2 UA — у розіграша може бути список призів. Run in Supabase → SQL Editor.
-- Requires 0006, 0032.
--
-- Досі приз був один рядок тексту — `prize`, — і цього вистачало, бо розіграш
-- справді розігрував одну річ. Мейджорський роздає дев'ять, і кожна має своє
-- місце: перше бере мишу, дев'яте — USP. Втиснути це в один рядок означає
-- або збрехати («дев'ять скінів»), або написати абзац, у якому ніхто не
-- знайде себе.
--
-- Тому список окремо, у `prizes`, і він упорядкований: перший елемент — за
-- перше місце. Порядок місць — це і є порядок масиву, окремої колонки з
-- номером немає свідомо: два джерела порядку рано чи пізно розійдуться, і
-- тоді незрозуміло, кому віддавати мишу.
--
-- Кожен елемент: `{ "title": "AK-47", "sub": "Point Disarray [MW]",
-- "img": "/prizes/…", "scale": 0.9 }`. `sub` і `img` необов'язкові, `scale` —
-- частка ширини коробки, яку займає картинка: ножі й миші поруч із AWP
-- інакше виглядали б однаковими за розміром, хоча вони не однакові.
--
-- `prize` лишається і лишається обов'язковим: це заголовок картки, і для
-- розіграшу з дев'ятьма призами він каже, що це взагалі таке.

alter table public.giveaways
  add column if not exists prizes jsonb not null default '[]'::jsonb;

-- Масив, а не словник: порядок має значення, і тільки масив його зберігає.
alter table public.giveaways
  drop constraint if exists giveaways_prizes_check;
alter table public.giveaways
  add constraint giveaways_prizes_check
  check (jsonb_typeof(prizes) = 'array');

