-- CS2 UA — «прохід» це 3:1 і 3:2, а не будь-яка трійка. Run in Supabase → SQL Editor.
-- Requires 0096.
--
-- 0096 написала правило влучання так:
--
--   when p_role = 'adv' then left(p_outcome, 1) = '3'
--
-- тобто прохід зараховувався на будь-який підсумок, що починається з трійки,
-- 3:0 включно. А кошик у картці підписаний буквально «3:1 3:2», і поруч із ним
-- стоїть окремий кошик «3:0», удвічі дорожчий — 150 проти 50 — саме тому, що
-- влучити в нього важче.
--
-- Тож людина бачила два різні кошики з різною ціною, а база вважала їх
-- частково одним. Команду, яка взяла 3:0, можна було покласти в дешевий кошик
-- і все одно отримати за неї очки; картка з обома трійками в проході брала сто
-- очок там, де мала нуль. На першій стадії це 140 таких влучань.
--
-- Правило в коді (`isHit` у `src/lib/major-pickem.ts`) міняється разом із цим
-- рядком і тією самою правкою: два джерела однієї формули — 0096 попереджала
-- про це прямо, і попередження лишається чинним.
--
-- Що НЕ робить ця міграція: вона не перераховує нічого заднім числом. Уже
-- зараховані стадії лишаються як є — `score_major_stage` дивиться тільки на
-- картки з порожнім `scored_at`. Перерахунок першої стадії, якщо він потрібен,
-- це окрема дія з окремим рішенням, бо він забирає очки в тих, кому їх уже
-- нарахували й про це сповістили.

create or replace function public.major_pick_hit(p_role text, p_outcome text)
returns boolean
language sql
immutable
as $$
  select case
           when p_outcome is null then false
           when p_role = 'adv'    then p_outcome in ('3-1', '3-2')
           else p_role = p_outcome
         end;
$$;

