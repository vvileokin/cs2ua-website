-- мейджор із нуля на гаманці, яким тут платять за все, — це не старт, а
-- зачинені двері, тож за замовчуванням тепер 1200. Наявним роздано окремо,
-- і роздано через `greatest`: у дев'яноста чотирьох лишалися залишки з Porto,
-- і забирати їх немає за що.

