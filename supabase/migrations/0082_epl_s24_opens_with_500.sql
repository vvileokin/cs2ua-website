-- CS2 UA — ESL Pro League S24 відкривається, у всіх знову по 500.
-- Run in Supabase → SQL Editor. Requires 0060, 0073, 0075, 0079.
--
-- Два попередні івенти лишили гаманці відкритими: 545 363 івент-поінтів усе ще
-- лежать на 642 профілях, найбільший — 81 310. Витратити їх нема де з 0079,
-- коли звичайна ставка перейшла на сезонні, тож це не баланс у грі, а слід
-- турніру, який скінчився в серпні.
--
-- Прибуток із них уже в сезонній колонці. Так працює правило з 0075: виграна
-- ставка одразу додає різницю в `points`, програна з сезонних не знімає. Тому
-- закриття не конвертує нічого — `settle_event_to_season` лише чистить гаманець
-- (0074). Викликати його тут означало б заплатити за Porto вдруге, а 0070
-- існує саме для того, щоб цього не сталося.
--
-- Отже: гаманець обнуляється до нового внеску, а не виплачується.
--
--     кожному 500 на EPL S24
--     дошка порожня, поки хтось не зробить першу дію
--     ставка на матч EPL списує івент-поінти, на будь-який інший — сезонні

begin;

-- ---------------------------------------------------------------------------
-- Новий внесок
-- ---------------------------------------------------------------------------
-- Рівно 500 кожному, включно з тими, хто лишився з нулем: турнір має бути
-- змаганням у читанні гри, а не в тому, хто скільки приніс із серпня.
update public.profiles
   set event_points = 500,
       event_joined_at = null;

-- Нові акаунти, що з'являться під час турніру, отримують те саме.
alter table public.profiles alter column event_points set default 500;

-- ---------------------------------------------------------------------------
-- Чий це гаманець
-- ---------------------------------------------------------------------------
-- Список із 0079: ставка на матч турніру зі списку списує івент-поінти, решта
-- сайту живе на сезонних. Порожній рядок тут — це мовчазний перехід усього
-- турніру на сезонну валюту, тому слаґ додається тим самим рухом, що й внесок.
insert into public.event_tournaments (slug) values ('esl-pro-league-s24')
on conflict (slug) do nothing;

commit;

