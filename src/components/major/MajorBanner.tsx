import Image from "next/image";

/**
 * Банер над сторінкою мейджора.
 *
 * Та сама бухта, що на головній: співвідношення 3:1, один файл на обидва
 * екрани, нічого не обрізається — на телефоні він просто менший. Тому й
 * картинка та сама, якою головна кличе сюди: людина приходить за банером і
 * бачить його ж угорі, тобто потрапила куди йшла.
 *
 * Без посилання, на відміну від головної. Там банер — оголошення, яке веде
 * на цю сторінку; тут вести нема куди, а клікабельна смуга, що нікуди не
 * веде, гірша за просто смугу.
 *
 * І без заголовка. `Hero` ховає в собі `sr-only` h1, бо на головній іншого
 * немає; тут h1 уже є в рядку стану, і другий зробив би сторінку з двома
 * заголовками — для пошуку й для читача з екранним диктором це поломка.
 */
export function MajorBanner({ image }: { image: string }) {
  return (
    <div className="relative aspect-[3/1] w-full overflow-hidden rounded-[4px] bg-[color-mix(in_oklch,var(--surface)_60%,var(--bg))]">
      <Image
        src={image}
        alt=""
        fill
        priority
        sizes="(min-width: 1024px) 1320px, 100vw"
        quality={90}
        className="object-cover object-center"
      />
    </div>
  );
}
