/**
 * H2H падає, коли росте решта рейтингу.
 *
 * Привід: B8 перемогли K27 і за формулою мали взяти +51, а взяли +27. Розбір
 * по компонентах показав, що три з чотирьох збіглись майже точно — LAN +28
 * при обіцяних +28, мережа +10 при +7, скальпи −1 при +1,5 — а H2H, якому я
 * давав +14, насправді дав −10.
 *
 * Пояснення в самому описі компонента на HLTV: H2H перераховується щоразу з
 * нуля, причому СПЕРШУ рахуються чотири інші компоненти й кожна команда
 * отримує «ranking starting point», і лише потім по цій новій висоті
 * перерозподіляються очки за всі матчі. Отже, коли твоя база підскочила, твої
 * старі перемоги над слабкими знецінюються, а старі поразки від сильних
 * дорожчають — і H2H іде вниз, компенсуючи частину приросту.
 *
 * Тут це міряється на трьох командах, які 28 жовтня зіграли по одному матчу.
 */
const CASES = [
  { team: "B8", opp: "K27", won: true,
    before: { L: 379, N: 97, O: 255, C: 268, H: 57 },
    after:  { L: 407, N: 107, O: 255, C: 267, H: 47 } },
  { team: "Nemiga", opp: "The MongolZ", won: true,
    before: { L: 462, N: 152, O: 270, C: 269, H: -18 },
    after:  { L: 466, N: 153, O: 269, C: 277, H: -10 } },
  { team: "Astralis", opp: "magic", won: true,
    before: { L: 477, N: 177, O: 295, C: 260, H: -30 },
    after:  { L: 479, N: 178, O: 294, C: 263, H: -24 } },
];

console.log("команда      Δбаза   ΔH2H   усього   ΔH2H якби лише пряма передача");
const pts = [];
for (const c of CASES) {
  const base = ["L", "N", "O", "C"].reduce((s, k) => s + (c.after[k] - c.before[k]), 0);
  const h = c.after.H - c.before.H;
  pts.push([base, h]);
  console.log(`  ${c.team.padEnd(11)}${(base >= 0 ? "+" : "") + base}`.padEnd(21) +
    `${(h >= 0 ? "+" : "") + h}`.padEnd(7) + `${(base + h >= 0 ? "+" : "") + (base + h)}`.padEnd(9) +
    `  перемога над ${c.opp}`);
}

/* Пряма підгонка ΔH2H = a − b·Δбаза. */
const n = pts.length;
const mx = pts.reduce((s, p) => s + p[0], 0) / n, my = pts.reduce((s, p) => s + p[1], 0) / n;
let sxy = 0, sxx = 0;
for (const [x, y] of pts) { sxy += (x - mx) * (y - my); sxx += (x - mx) ** 2; }
const b = sxy / sxx, a = my - b * mx;
console.log(`\nΔH2H ≈ ${a.toFixed(1)} ${b >= 0 ? "+" : "−"} ${Math.abs(b).toFixed(2)}·Δбаза`);
console.log("перевірка:");
for (const [x, y] of pts) console.log(`  Δбаза ${String(x).padStart(3)} → модель ${(a + b * x).toFixed(1)}, факт ${y}`);
console.log(`\nтобто кожне очко, здобуте в чотирьох компонентах, повертає` +
  ` ${Math.abs(b).toFixed(2)} очка назад через H2H.`);
console.log("На трьох точках це не закон, а напрям — але напрям однозначний і великий:");
console.log("для B8 він з'їв 24 очка з 51, тобто половину матчу.");
